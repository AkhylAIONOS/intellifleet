import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {createServer} from 'vite';
const dom=new JSDOM('<html><body></body></html>',{url:'http://localhost/',pretendToBeVisual:true});
for(const key of ['window','document','HTMLElement','Element','Node','navigator','localStorage','sessionStorage'])Object.defineProperty(globalThis,key,{value:dom.window[key],configurable:true});
const React=await import('react');
const {render,act,fireEvent,waitFor,cleanup}=await import('@testing-library/react');
const server=await createServer({optimizeDeps:{noDiscovery:true,include:[]},server:{middlewareMode:true,hmr:false,ws:false},appType:'custom'});
const nativeTimeout=globalThis.setTimeout,nativeClear=globalThis.clearTimeout;
const polling=new Set();
globalThis.setTimeout=(fn,ms,...args)=>{const handle=nativeTimeout(fn,ms,...args);if(ms===10000)polling.add(handle);return handle;};
globalThis.clearTimeout=handle=>{polling.delete(handle);return nativeClear(handle);};
try{
 const {controlTowerApi:api}=await server.ssrLoadModule('/src/api/controlTower.ts');
 const {ControlTower}=await server.ssrLoadModule('/src/components/ControlTower.tsx');
 const pending=[],calls=[];
 api.runs=params=>{calls.push(params);return new Promise((resolve,reject)=>pending.push({resolve,reject,params}));};
 api.summary=async()=>({total_runs:0,air_runs:0,surface_runs:0,statuses:{},critical_lanes:0,critical_lanes_at_risk:0});
 api.recipients=async()=>({emails:[]});
 const ui=render(React.createElement(ControlTower));
 assert.ok(ui.getByText('Loading operational runs…'));
 assert.equal(ui.queryByText(/No matching operational runs/),null);
 assert.equal(polling.size,1,'one Control Tower polling timer');
 await act(async()=>fireEvent.click(ui.getByRole('button',{name:'AIR LINEHAUL'})));
 assert.equal(polling.size,1,'filter change replaces polling timer');
 assert.equal(pending.length,2);
 await act(async()=>pending[1].resolve({runs:[],total:0}));
 assert.ok(ui.getByText(/No matching operational runs/));
 await act(async()=>pending[0].resolve({runs:[],total:99}));
 assert.ok(ui.getByText(/Air linehaul · 0 matching runs/),'stale Surface response cannot replace Air result');
 await act(async()=>fireEvent.change(ui.getByLabelText('Search network'),{target:{value:'BOM'}}));
 await waitFor(()=>assert.equal(calls.at(-1).search,'BOM'));
 await act(async()=>pending.at(-1).reject(new Error('offline')));
 assert.ok(ui.getByRole('alert'));
 assert.equal(ui.queryByText(/No matching operational runs/),null,'failed fetch is not an empty network');
 await act(async()=>fireEvent.click(ui.getByRole('button',{name:'Refresh operations'})));
 await act(async()=>pending.at(-1).resolve({runs:[],total:28}));
 assert.equal(ui.queryByRole('alert'),null,'successful refresh clears old connection error');
 await act(async()=>fireEvent.click(ui.getByRole('button',{name:'Next'})));
 assert.equal(calls.at(-1).offset,25);
 await act(async()=>pending.at(-1).resolve({runs:[],total:28}));
 api.con=async()=>{throw {response:{status:404,data:{detail:'CON not found'}}};};
 await act(async()=>fireEvent.change(ui.getByLabelText('Search CON'),{target:{value:'MISSING-CON'}}));
 await act(async()=>fireEvent.click(ui.getByRole('button',{name:'Locate package'})));
 assert.ok(ui.getByText('CON not found'));
 cleanup();
 assert.equal(polling.size,0,'unmount cancels polling');
 console.log('PASS: loading/error/empty distinctions, stale response isolation, debounced search, pagination, missing CON, one polling timer and cleanup');
}finally{
 cleanup();globalThis.setTimeout=nativeTimeout;globalThis.clearTimeout=nativeClear;
 await server.close();dom.window.close();
}
